#!/usr/bin/env node
/**
 * verify-no-undefined-names — a plain `no-undef` over every source file.
 *
 * REBUILT 23 August 2026 at 3.368.1.
 *
 * WHY THIS CHECK EXISTS. From lesson 5.2: `shieldedStrideBonus` was
 * *called* in the attack workflow and never *imported*. Every weapon
 * attack against a target threw and abandoned itself, and had done since
 * Shielded Stride landed — hidden behind `targetActor ? … : 0`, so
 * attacking with nothing targeted still worked, which is what anyone
 * tries first. The caller check could not help: the name *appeared*.
 * Only resolving the name against its scope catches this shape, and on
 * its first run the original found four more crashes just like it.
 *
 * WHY IT FAILS ON UNPARSEABLE FILES. Lesson 5.4: the original reported
 * "no undefined names (warnings only)" on seven files it could not
 * parse. A checker that cannot read a file has not checked it, and the
 * cheerful summary line was worse than no check at all. Parse failures
 * here are failures, counted and named — see tools/lib/sources.mjs.
 *
 * WHERE THE GLOBALS LIST COMES FROM. tools/foundry-globals.json, which
 * was generated by reading `globalThis` off a *running* Foundry client
 * rather than by hand. A hand-written list is a guess about someone
 * else's API surface; every name it forgets becomes a false positive
 * that trains the reader to ignore this check's output. Regenerate it
 * with `node tools/generate-foundry-globals.mjs` against a live world.
 */

import fs from "node:fs";
import path from "node:path";
import { analyze } from "eslint-scope";
import { findSourceFiles, parseAll, reportParseFailures, SYSTEM_ROOT } from "./lib/sources.mjs";

const GLOBALS_FILE = path.join(SYSTEM_ROOT, "tools", "foundry-globals.json");

/**
 * ECMAScript's own globals. These are the ones the language guarantees,
 * independent of host — kept separate from the host list so it is always
 * clear which names are the language's and which are Foundry's.
 */
const ECMA_GLOBALS = [
  "globalThis", "Infinity", "NaN", "undefined",
  "eval", "isFinite", "isNaN", "parseFloat", "parseInt",
  "decodeURI", "decodeURIComponent", "encodeURI", "encodeURIComponent",
  "Object", "Function", "Boolean", "Symbol", "Error", "AggregateError",
  "EvalError", "RangeError", "ReferenceError", "SyntaxError", "TypeError", "URIError",
  "Number", "BigInt", "Math", "Date", "String", "RegExp",
  "Array", "Int8Array", "Uint8Array", "Uint8ClampedArray", "Int16Array", "Uint16Array",
  "Int32Array", "Uint32Array", "Float32Array", "Float64Array", "BigInt64Array", "BigUint64Array",
  "Map", "Set", "WeakMap", "WeakSet", "WeakRef", "FinalizationRegistry",
  "ArrayBuffer", "SharedArrayBuffer", "DataView", "Atomics", "JSON",
  "Promise", "Reflect", "Proxy", "Intl",
  "arguments"
];

function loadHostGlobals() {
  if (!fs.existsSync(GLOBALS_FILE)) {
    throw new Error(
      `Missing ${path.relative(SYSTEM_ROOT, GLOBALS_FILE)}.\n` +
        `Generate it against a running Foundry world with:\n` +
        `  node tools/generate-foundry-globals.mjs\n` +
        `Refusing to run with a guessed globals list — a wrong list turns this check into noise.`
    );
  }
  const data = JSON.parse(fs.readFileSync(GLOBALS_FILE, "utf8"));
  return { names: new Set(data.names), meta: data };
}

/**
 * Every identifier a file uses that resolves to no declaration anywhere
 * in its scope chain — i.e. that it expects to find on the global object.
 */
function unresolvedNames(parsed) {
  const manager = analyze(parsed.ast, {
    ecmaVersion: 2024,
    sourceType: "module",
    ignoreEval: true
  });
  const out = [];
  for (const ref of manager.globalScope.through) {
    // `through` is exactly "references that escaped every scope". A write
    // to an undeclared name is as much a bug as a read, so both count.
    out.push({
      name: ref.identifier.name,
      line: ref.identifier.loc?.start.line ?? null,
      column: (ref.identifier.loc?.start.column ?? 0) + 1
    });
  }
  return out;
}

export function run({ quiet = false } = {}) {
  const { names: hostGlobals, meta } = loadHostGlobals();
  const known = new Set([...ECMA_GLOBALS, ...hostGlobals]);

  const files = findSourceFiles();
  const { parsed, failed } = parseAll(files);

  const findings = [];
  for (const p of parsed) {
    for (const ref of unresolvedNames(p)) {
      if (known.has(ref.name)) continue;
      findings.push({ file: p.rel, ...ref });
    }
  }

  const hadParseFailures = reportParseFailures(failed, "verify-no-undefined-names");

  if (findings.length) {
    process.stderr.write(`\nverify-no-undefined-names: ${findings.length} undefined name(s)\n`);
    // Grouped by file, because these almost always cluster — one missing
    // import accounts for every use of that name in the file, and a flat
    // list makes one bug look like six.
    const byFile = new Map();
    for (const f of findings) {
      if (!byFile.has(f.file)) byFile.set(f.file, []);
      byFile.get(f.file).push(f);
    }
    for (const [file, list] of [...byFile].sort()) {
      process.stderr.write(`  ${file}\n`);
      const byName = new Map();
      for (const f of list) {
        if (!byName.has(f.name)) byName.set(f.name, []);
        byName.get(f.name).push(f.line);
      }
      for (const [name, lines] of [...byName].sort()) {
        process.stderr.write(`    ${name}  (line${lines.length > 1 ? "s" : ""} ${lines.join(", ")})\n`);
      }
    }
  }

  const ok = !findings.length && !hadParseFailures;
  if (!quiet) {
    process.stdout.write(
      ok
        ? `verify-no-undefined-names: OK — ${parsed.length} files parsed and checked ` +
            `against ${known.size} known globals (Foundry ${meta.foundryVersion ?? "?"}).\n`
        : `verify-no-undefined-names: FAILED — ${findings.length} undefined name(s), ` +
            `${failed.length} unparseable file(s).\n`
    );
  }
  return { ok, findings, failed, filesChecked: parsed.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  let result;
  try {
    result = run();
  } catch (err) {
    process.stderr.write(`verify-no-undefined-names: ${err.message}\n`);
    process.exit(2);
  }
  process.exit(result.ok ? 0 : 1);
}
