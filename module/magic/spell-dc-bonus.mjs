/**
 * Spell save DC bonuses a caster declares, scoped by the spell's traits
 * (3.627.0).
 *
 * Pillars of Faith, Chapter 9 — Soul-Magic Dominion (Unliving Lich): "You
 * gain a +1 racial bonus to Spellcraft checks and spell save DCs for spells
 * with the soul trait. This bonus applies only to your own spellcasting and
 * innate spells." The Spellcraft half is an ordinary conditional; nothing
 * carried the DC half — the save DC had no channel for a scoped bonus.
 *
 *   flags.trg-prime.spellDCBonus = { label, value: 1, type: "race", traits: ["soul"] }
 *
 * Typed as every bonus is: the highest of a type, untyped summed. An item's
 * spell (a staff, a scroll) is not "your own spellcasting"; the caller does
 * not ask for one.
 *
 * Pure.
 */
const SYSTEM_ID = "trg-prime";
const lower = (v) => String(v ?? "").trim().toLowerCase();
const traitList = (v) => (Array.isArray(v) ? v : String(v ?? "").split(/[,;]/)).map(lower).filter(Boolean);

/**
 * The declared rows of one flag that apply to this cast, after stacking.
 *
 * SHARED BY THE SAVE DC AND (3.695.0) THE SPELL ATTACK. Pillars of Faith's
 * Eternal Resonance (Graham's ruling U7, 16 Nov 2026): "+1-racial bonus to
 * attack rolls and Save DCs generated by innate spells", ruled to cover all
 * innate spells. The DC half had a channel (`innateOnly`); the attack half
 * had none, and the module's casting option never reached an innate cast,
 * which shows no Casting Conditions prompt. So the attack reads a twin flag:
 *
 *   flags.trg-prime.spellAttackBonus = { label, value, type, traits?, innateOnly?, itemCasts? }
 *
 * AN ITEM'S SPELL (3.695.0): not "your own spellcasting", so skipped as
 * before, unless the row says `itemCasts: true` (an item's innate spell is
 * still an innate spell, for that ruling).
 *
 * @param {Iterable} effects the caster's applied effects
 * @param {string} flagName "spellDCBonus" or "spellAttackBonus"
 * @param {string|string[]} spellTraits
 * @returns {Array<{label: string, value: number, type: string}>}
 */
function declaredSpellBonuses(effects = [], flagName = "spellDCBonus", spellTraits = [], { innate = false, itemCast = false } = {}) {
  const have = new Set(traitList(spellTraits));
  const rows = [];
  for (const effect of Array.from(effects ?? [])) {
    if (effect?.disabled) continue;
    const raw = effect?.flags?.[SYSTEM_ID]?.[flagName];
    for (const row of Array.isArray(raw) ? raw : (raw ? [raw] : [])) {
      const value = Math.trunc(Number(row?.value) || 0);
      if (!value) continue;
      // INNATE SPELLS ONLY (3.669.0; Inner Tempest's Elemental Attunement:
      // "innate spell save DCs for spells with a trait matching your racial
      // element"): `innateOnly: true` asks the caller whether this one is.
      if (row?.innateOnly === true && innate !== true) continue;
      if (itemCast === true && row?.itemCasts !== true) continue;
      const wanted = traitList(row?.traits);
      if (wanted.length && !wanted.some((t) => have.has(t))) continue;
      rows.push({ label: String(row?.label ?? "").trim() || (flagName === "spellAttackBonus" ? "Spell attack bonus" : "Spell DC bonus"), value, type: lower(row?.type) || "untyped" });
    }
  }
  const best = new Map();
  const out = [];
  for (const row of rows) {
    if (row.type === "untyped" || row.value < 0) { out.push(row); continue; }
    const held = best.get(row.type);
    if (!held || row.value > held.value) best.set(row.type, row);
  }
  return [...best.values(), ...out];
}

/**
 * @param {Iterable} effects the caster's applied effects
 * @param {string|string[]} spellTraits
 * @returns {Array<{label: string, value: number, type: string}>} the bonuses that apply, after stacking
 */
export function declaredSpellDCBonuses(effects = [], spellTraits = [], { innate = false, itemCast = false } = {}) {
  return declaredSpellBonuses(effects, "spellDCBonus", spellTraits, { innate, itemCast });
}

/** The spell attack's twin (3.695.0). Rows join the attack pool, stacked there. */
export function declaredSpellAttackBonuses(effects = [], spellTraits = [], { innate = false, itemCast = false } = {}) {
  return declaredSpellBonuses(effects, "spellAttackBonus", spellTraits, { innate, itemCast });
}
